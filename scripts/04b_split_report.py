"""Split-validation report (markdown) from the saved split files and diagnostics."""
import argparse
import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from stylebench.config import ARTIFACTS  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("split_root")
a = ap.parse_args()
root = ARTIFACTS / "splits" / a.split_root
summ = pd.read_csv(root / "split_summary.csv")
core = pd.read_csv(root / "core_style_table.csv", index_col=0)
cand = json.load(open(root / "genre_holdout_candidates.json")) if (root / "genre_holdout_candidates.json").exists() else None
L = [f"# Split-validation report: {a.split_root}\n",
     "Generated by `scripts/04b_split_report.py` from `artifacts/splits/%s/`. Every split file passed "
     "`stylebench.data.validate.validate_split` (raises on any violation) before it was written.\n" % a.split_root,
     "## Core style set (metadata-only rules)\n",
     f"Pool: images with every required label. Kept styles: {int((core.excluded_reason.isna() | (core.excluded_reason == '')).sum())}"
     f" / {len(core)}.\n", "Excluded styles and reasons:\n"]
ex = core[core.excluded_reason.fillna("") != ""]
L.append(ex.to_markdown() if len(ex) else "(none)")
if cand:
    L.append(f"\n\nFeasible held-out genre sets: {cand['n_candidates']} (each seed draws one uniformly).\n")
L.append("\n## Per protocol and seed\n")
cols = ["seed", "protocol", "n_train_fit", "n_val", "n_sel_excluded", "n_train_total", "n_test", "n_styles",
        "n_test_artists", "artist_overlap", "genre_overlap", "near_dup_cross", "n_dropped_styles", "test_genres",
        "all_checks_pass"]
L.append(summ[[c for c in cols if c in summ.columns]].to_markdown(index=False))
L.append("\n\n`artist_overlap` / `genre_overlap` = number of artists / genres present on both the train side "
         "(train + val + selection-excluded) and the test side. They must be 0 where the protocol requires "
         "disjointness (artist_disjoint, joint, mf_artist, mf_joint for artists; genre_disjoint, joint, mf_genre, "
         "mf_joint for genres); IID overlap is reported, not constrained.\n")
L.append("\n## Assertions\n")
rows = []
for p in sorted(summ.protocol.unique()):
    for f in sorted((root / p).glob("seed*.json")):
        d = json.load(open(f))
        rows.append({"protocol": p, "seed": d["seed"], **{k: v for k, v in d["checks"].items()}})
L.append(pd.DataFrame(rows).to_markdown(index=False))
L.append("\n\n## Styles removed per seed\n")
for p in ["iid", "mf_iid"]:
    for f in sorted((root / p).glob("seed*.json")) if (root / p).exists() else []:
        d = json.load(open(f))
        dr = d.get("dropped_styles", {})
        mf = d.get("mf_dropped", {})
        if p == "iid":
            L.append(f"- seed {d['seed']} (all four main protocols): " + (json.dumps(dr) if dr else "none"))
        else:
            L.append(f"- seed {d['seed']} (matched factorial only, half-cell test support): " + (json.dumps(mf) if mf else "none"))
L.append("\n## Per-style counts (mean over seeds; train side = train + val + selection-excluded)\n")
for p in sorted(summ.protocol.unique()):
    recs = []
    for f in sorted((root / p).glob("seed*.json")):
        for s, v in json.load(open(f))["per_style"].items():
            recs.append({"style": s, **v})
    t = pd.DataFrame(recs).groupby("style").mean().round(1)
    L.append(f"\n### {p}\n")
    L.append(t.to_markdown())
(ARTIFACTS / "reports" / f"{a.split_root}_split_report.md").write_text("\n".join(L))
print("written", ARTIFACTS / "reports" / f"{a.split_root}_split_report.md")
