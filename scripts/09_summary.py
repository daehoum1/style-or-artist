"""Cross-dataset outputs: Table 1 (dataset statistics),
per-style gap analysis, and artifacts/final/SUMMARY.md."""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from stylebench.config import ARTIFACTS, load_yaml  # noqa: E402
from stylebench.evaluation.statistics import paired_summary  # noqa: E402
from stylebench.models.base import encoder_configs  # noqa: E402

F = ARTIFACTS / "final"
F.mkdir(exist_ok=True)
A = load_yaml("configs/experiments/analysis.yaml")
ENC = list(encoder_configs())
# WeART excluded from the paper (author decision 2026-10-09: public release has no style labels)
DS = ["wikiart", "multitask_painting"]
NAME = {"wikiart": "WikiArt", "multitask_painting": "MultitaskPainting100k"}

# ---------------- Table 1
rows = []
for d in DS:
    p = ARTIFACTS / "reports" / f"{d}_audit.json"
    if not p.exists():
        continue
    a = json.load(open(p))
    c = a["cleaned"]
    s = ARTIFACTS / "splits" / d / "split_summary.csv"
    ss = pd.read_csv(s) if s.exists() else None
    core = pd.read_csv(ARTIFACTS / "splits" / d / "core_style_table.csv", index_col=0) if s.exists() else None
    rows.append({"dataset": NAME[d], "raw images": a["raw"]["n_images"], "after cleaning": c["n_images"],
                 "artists": c["n_artists"], "styles": c["n_styles"], "genres": c["n_genres"] if c["n_genres"] else "-",
                 "missing genre": c["missing"]["genre"] if c["n_genres"] else "-",
                 "style max/min ratio": c["style_imbalance"]["max_min_ratio"],
                 "styles per artist (mean)": c["styles_per_artist"]["mean"],
                 "controlled pool": int(ss[(ss.protocol == "iid") & (ss.seed == 0)][["n_train_total", "n_test"]].sum(1).iloc[0]) if ss is not None else None,
                 "core styles": int((core.excluded_reason.fillna("") == "").sum()) if core is not None else None})
t1 = pd.DataFrame(rows)
t1.to_csv(F / "table1_datasets.csv", index=False)
(F / "table1_datasets.tex").write_text(t1.to_latex(index=False))

# ---------------- per-style gaps (primary evaluator, recall, mean over seeds, then encoders)
per_style = []
for d in ["wikiart", "multitask_painting"]:
    files = sorted((ARTIFACTS / "results" / "style_eval" / d).glob("*_per_class.parquet"))
    if not files:
        continue
    pc = pd.concat([pd.read_parquet(f) for f in files])
    pc = pc[pc.evaluator == A["primary_evaluator"]]
    m = pc.groupby(["encoder", "protocol", "style"]).recall.mean().unstack("protocol")
    mm = m.groupby("style").mean()
    for gname, (x, y) in {**A["gaps"], **A["mf_effects"]}.items():
        if x in mm and y in mm:
            mm[gname] = mm[x] - mm[y]
    core = pd.read_csv(ARTIFACTS / "splits" / d / "core_style_table.csv", index_col=0)
    mm = mm.join(core[["n_images", "n_artists"]])
    mm.insert(0, "dataset", d)
    per_style.append(mm.reset_index())
if per_style:
    ps = pd.concat(per_style)
    ps.to_csv(F / "per_style_recall_gaps.csv", index=False)

# ---------------- SUMMARY.md
L = ["# Summary of results (auto-generated by scripts/09_summary.py)\n",
     f"Primary evaluator: {A['primary_evaluator']}; primary metric: {A['primary_metric']}. Probe: "
     f"{A['probe_evaluator']} {A['probe_metric']}. Numbers in %, mean over split seeds.\n",
     "## Table 1: datasets\n", t1.to_markdown(index=False)]
for d in DS:
    p = F / d / "encoder_level.csv"
    if not p.exists():
        continue
    E = pd.read_csv(p, index_col=0)
    cols = [c for c in ["iid", "artist_disjoint", "genre_disjoint", "joint", "artist_gap", "genre_gap", "joint_gap",
                        "mf_iid", "mf_artist", "mf_genre", "mf_joint", "artist_effect", "genre_effect", "joint_effect",
                        "style", "artist", "within_style_artist", "genre", "within_style_genre"] if c in E]
    L.append(f"\n## {NAME[d]}: encoder-level (bAcc / probes x100)\n")
    L.append((100 * E[cols]).round(1).to_markdown())
    for k in ["primary", "secondary"]:
        cp = F / d / f"correlations_{k}.csv"
        if cp.exists():
            c = pd.read_csv(cp)
            if k == "secondary":
                c = c[c.gap.isin(["artist_gap", "genre_gap", "joint_gap", "artist_effect", "genre_effect", "joint_effect"])]
            L.append(f"\n### {NAME[d]}: {k} correlations (Spearman over encoders)\n")
            L.append(c.round(3).to_markdown(index=False))
    mr = F / d / "master_results.json"
    if mr.exists():
        r = json.load(open(mr))["rankings"]
        L.append("\nRankings: " + json.dumps({k: v for k, v in r.items() if k.startswith("kendall") and "per_seed" not in k}))
if per_style:
    L.append("\n## Per-style recall gaps (mean over encoders)\n")
    L.append((ps.set_index(["dataset", "style"])[[c for c in ["n_artists", "iid", "artist_gap", "genre_gap", "joint_gap", "artist_effect", "genre_effect"] if c in ps]]
              .round(3)).to_markdown())
(F / "SUMMARY.md").write_text("\n".join(L) + "\n")
print("\n".join(L)[:6000])
